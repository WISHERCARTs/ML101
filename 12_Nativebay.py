"""
=============================================================
Naive Bayes Classification - การจำแนกประเภทด้วย Naive Bayes
=============================================================
โปรแกรมนี้ใช้ Gaussian Naive Bayes ในการจำแนกประเภทดอกไอริส (Iris)
ชุดข้อมูล Iris มี 3 ชนิด: Setosa(0), Versicolor(1), Virginica(2)
"""

# =============================================================
# STEP 1: Import Libraries - นำเข้าไลบรารีที่จำเป็น
# =============================================================
from sklearn.datasets import load_iris          # โหลดชุดข้อมูล Iris ที่มีมาใน sklearn
from sklearn.model_selection import train_test_split  # แบ่งข้อมูลเป็น train/test
from sklearn.naive_bayes import GaussianNB      # โมเดล Gaussian Naive Bayes
from sklearn.metrics import accuracy_score      # วัดความแม่นยำของโมเดล

# =============================================================
# STEP 2: Load Dataset - โหลดชุดข้อมูล
# =============================================================
iris = load_iris()      # โหลดชุดข้อมูลดอกไอริส
x = iris['data']        # Features: ข้อมูลลักษณะของดอกไม้ (4 คอลัมน์)
                        # - ความยาวกลีบเลี้ยง, ความกว้างกลีบเลี้ยง
                        # - ความยาวกลีบดอก, ความกว้างกลีบดอก
y = iris['target']      # Labels: ชนิดของดอกไม้ (0, 1, 2)

# =============================================================
# STEP 3: Split Data - แบ่งข้อมูลสำหรับ Train และ Test
# =============================================================
# test_size=0.2 หมายถึง ใช้ 20% เป็นข้อมูลทดสอบ, 80% เป็นข้อมูลฝึก
# random_state=42 หมายถึง กำหนด seed ให้สุ่มได้ผลเหมือนกันทุกครั้ง
train_x, test_x, train_y, test_y = train_test_split(x, y, test_size=0.2, random_state=42)
# train_x, train_y = ข้อมูลสำหรับฝึกโมเดล
# test_x, test_y = ข้อมูลสำหรับทดสอบโมเดล

# =============================================================
# STEP 4: Create & Train Model - สร้างและฝึกโมเดล
# =============================================================
model = GaussianNB()            # สร้างโมเดล Gaussian Naive Bayes
model.fit(train_x, train_y)     # ฝึกโมเดลด้วยข้อมูล training
                                # โมเดลจะเรียนรู้ความสัมพันธ์ระหว่าง features กับ labels

# =============================================================
# STEP 5: Predict - ทำนายผลลัพธ์
# =============================================================
y_pred = model.predict(test_x)  # ทำนายชนิดดอกไม้จากข้อมูล test
                                # y_pred = ผลการทำนาย (array ของ 0, 1, 2)

# =============================================================
# STEP 6: Evaluate - วัดผลความแม่นยำ
# =============================================================
# เปรียบเทียบผลทำนาย (y_pred) กับคำตอบจริง (test_y)
accuracy = accuracy_score(test_y, y_pred)
print(f"Accuracy: {accuracy * 100:.2f}%")   # แสดงความแม่นยำเป็นเปอร์เซ็นต์

