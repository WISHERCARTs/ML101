"""
================================================================================
                    สรุป: PCA (Principal Component Analysis)
================================================================================

📌 PCA คืออะไร?
   - เทคนิคการ "ลดมิติข้อมูล" (Dimensionality Reduction) 
   - ยังคงรักษาความสัมพันธ์ระหว่างข้อมูลไว้

--------------------------------------------------------------------------------
🎯 ทำไมต้องใช้ PCA?
--------------------------------------------------------------------------------
   | ปัญหา                              | PCA ช่วยได้ยังไง                    |
   |------------------------------------|-------------------------------------|
   | มีตัวแปร 50 ตัว แต่ไม่ได้ใช้ทั้งหมด | เลือกเฉพาะตัวแปรที่สำคัญ            |
   | โมเดลทำงานช้า                      | ลดขนาดข้อมูล → ฝึกโมเดลเร็วขึ้น     |
   | Matrix ซับซ้อน                     | ทำให้ข้อมูลกระชับ เข้าใจง่าย         |

--------------------------------------------------------------------------------
🔧 หลักการทำงาน
--------------------------------------------------------------------------------
   1. สร้าง Component - ตัวแปรใหม่ที่ไม่สัมพันธ์กัน
   2. Component แรก - มีค่า variance สูงสุด (อธิบายข้อมูลได้มากที่สุด)
   3. Component ถัดไป - variance ลดลงตามลำดับ
   4. เลือกใช้ - Component ที่ครอบคลุม variance 80-90% ก็เพียงพอ

--------------------------------------------------------------------------------
✅ ข้อดี
--------------------------------------------------------------------------------
   - ไม่ทำลายข้อมูลต้นฉบับ
   - แค่เปลี่ยนมุมมองข้อมูลใหม่ให้กระชับขึ้น
   - เหมาะสำหรับข้อมูลที่มีหลายตัวแปร (High-dimensional data)

🧠 เปรียบเทียบง่ายๆ:
   เหมือนการ "ย่อหนังสือ 10 บท เหลือ 3 บทสำคัญ" 
   โดยยังครอบคลุมเนื้อหาหลักได้ 80-90%

================================================================================
"""

from sklearn.datasets import make_blobs # make_blobs คือ function ที่สร้างข้อมูลสุ่ม
from sklearn.decomposition import PCA # PCA คือ function ที่ทำ PCA
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sb

x, y = make_blobs(n_samples=100, n_features=10)
pca = PCA(n_components=4)
pca.fit_transform(x)


# print("Shape of x: ", x.shape)
# print("PCA: ", pca.fit_transform(x).shape) #fit คือ function ที่ทำ PCA และ return ค่าที่ได้

# pca.
df = pd.DataFrame({'var' : pca.explained_variance_ratio_ , 'pc' : ['pc1', 'pc2', 'pc3', 'pc4']})
sb.barplot(x='pc', y='var', data=df, color='c')
plt.show()
